window.t = function(key) { return dict[window.currentLang][key] || key; };

window.applyLanguage = function() {
    let tempId = dict['id']['lbl_rs'];
    let tempEn = dict['en']['lbl_rs'];
    let tempKursiId = dict['id']['lbl_kursi']; let tempKursiEn = dict['en']['lbl_kursi'];
    let tempKursiThId = dict['id']['lbl_kursi_th']; let tempKursiThEn = dict['en']['lbl_kursi_th'];
    let tempKursiLabelId = dict['id']['lbl_kursi_label']; let tempKursiLabelEn = dict['en']['lbl_kursi_label'];
    let isMeja = false;
    if(window.appState.currentEventId) {
        const evt = LS.getEvents().find(e => e.id === window.appState.currentEventId);
        if (evt && (evt.type === 'Internal' || evt.type === 'Lain-lain')) {
            dict['id']['lbl_rs'] = 'Asal Instansi';
            dict['en']['lbl_rs'] = 'Institution Origin';
        }
        if (evt && evt.seatLabelType === 'meja') {
            isMeja = true;
            dict['id']['lbl_kursi'] = 'Nomor Meja (Opsional)'; dict['en']['lbl_kursi'] = 'Table Number (Optional)';
            dict['id']['lbl_kursi_th'] = 'Meja'; dict['en']['lbl_kursi_th'] = 'Table';
            dict['id']['lbl_kursi_label'] = 'Nomor Meja'; dict['en']['lbl_kursi_label'] = 'Table Number';
        }
    }

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if(dict[window.currentLang][key]) el.innerHTML = dict[window.currentLang][key];
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if(dict[window.currentLang][key]) el.setAttribute('placeholder', dict[window.currentLang][key]);
    });

    document.querySelectorAll('[data-i18n-title]').forEach(el => {
        const key = el.getAttribute('data-i18n-title');
        if(dict[window.currentLang][key]) el.setAttribute('title', dict[window.currentLang][key]);
    });

    // Ikon "kursi" pada form pendaftaran & preview QR ikut menyesuaikan bila event memakai
    // istilah "Nomor Meja" — fa-chair untuk kursi, fa-utensils untuk representasi meja
    // (fa-table sebelumnya dipakai, tapi bentuknya menyerupai tabel data/spreadsheet,
    // bukan meja fisik, sehingga membingungkan).
    const seatIconClass = isMeja ? 'fa-utensils' : 'fa-chair';
    const inputKursiIcon = document.getElementById('input-kursi-icon');
    if (inputKursiIcon) inputKursiIcon.className = `fa-solid ${seatIconClass} absolute left-4 top-1/2 -translate-y-1/2 text-slate-400 dark:text-slate-500 text-sm`;

    dict['id']['lbl_rs'] = tempId;
    dict['en']['lbl_rs'] = tempEn;
    dict['id']['lbl_kursi'] = tempKursiId; dict['en']['lbl_kursi'] = tempKursiEn;
    dict['id']['lbl_kursi_th'] = tempKursiThId; dict['en']['lbl_kursi_th'] = tempKursiThEn;
    dict['id']['lbl_kursi_label'] = tempKursiLabelId; dict['en']['lbl_kursi_label'] = tempKursiLabelEn;

    const selLang = document.getElementById('app-language');
    if (selLang) selLang.value = window.currentLang;
};

window.changeLanguage = function(lang) {
    window.currentLang = lang;
    localStorage.setItem('qis_lang', lang);
    window.applyLanguage();
    window.updateHeaderDateTime();
    window.renderStorageMeter();
    window.renderAppVersionInfo();
    window.renderUserManageSummary();
    if(document.getElementById('tab-content-dashboard') && document.getElementById('tab-content-dashboard').classList.contains('active')) window.renderDashboard();
    if(document.getElementById('view-app') && !document.getElementById('view-app').classList.contains('view-hidden')) window.renderTable();
};
